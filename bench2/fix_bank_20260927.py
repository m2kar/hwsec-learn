def main():
    check_only = "--check" in sys.argv
    with open(CSV_PATH, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        fieldnames = reader.fieldnames

    n = 0
    for r in rows:
        qid = r["题号"].strip()
        if qid not in FIXES:
            continue
        fix = FIXES[qid]
        # 断言旧答案与预期一致
        if qid in EXPECTED_OLD_ANSWER:
            old = re.sub(r"[^A-G]", "", r["答案"].strip().upper()) if (re := __import__("re")) else r["答案"]
            assert old == EXPECTED_OLD_ANSWER[qid], f"{qid} 当前答案 {old!r} 与预期 {EXPECTED_OLD_ANSWER[qid]!r} 不符，请先核对文件是否被并发修改"
        if qid in EXPECTED_OLD_OPTIONS:
            k, old_opt = EXPECTED_OLD_OPTIONS[qid]
            cur = (r.get(f"选项{k}") or "").strip()
            assert cur == old_opt, f"{qid} 选项{k} 与预期不符：\n当前: {cur!r}\n预期: {old_opt!r}"
        if check_only:
            print(f"[check] {qid} 预期旧值匹配")
            n += 1
            continue
        if "answer" in fix:
            r["答案"] = fix["answer"]
        if "analysis" in fix:
            r["解析"] = fix["analysis"]
        if "options" in fix:
            for k, v in fix["options"].items():
                r[f"选项{k}"] = v
        n += 1

    print(f"{'校验' if check_only else '修订'} {n} 题")
    if check_only:
        return
    tmp = CSV_PATH.with_suffix(".csv.tmp")
    with open(tmp, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, quoting=csv.QUOTE_ALL, lineterminator="\r\n")
        w.writeheader()
        w.writerows(rows)
    tmp.replace(CSV_PATH)
    print(f"已写入 {CSV_PATH}")


if __name__ == "__main__":
    main()
