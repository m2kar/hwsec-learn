def rotate(items, n):
    n %= len(items)
    return items[n:] + items[:n]


def letters_for(correct_indices):
    return "".join(chr(65 + i) for i in sorted(correct_indices))


def make_questions(records, prefix, start, tier):
    rows = []
    for i, (domain, topic, truth, action, false1, false2, tag) in enumerate(records):
        qid = f"{prefix}{start + i:03d}"
        choices = [(truth, True), (false1, False), (false2, False), ("只凭宣传、单次测试或默认配置即可判断安全性。", False)]
        choices = rotate(choices, i)
        answer = letters_for([j for j, (_, ok) in enumerate(choices) if ok])
        opts = [text for text, _ in choices] + ["", "", ""]
        rows.append([qid, "单选", domain, tier, f"在“{topic}”的工程评审中，以下哪项判断正确？", *opts, answer, f"{truth}。工程上应{action}；其余选项混淆了安全目标、攻击面或防护边界。", tag])

        qid = f"{prefix}{start + 50 + i:03d}"
        choices = [(truth, True), (action, True), (false1, False), (false2, False), ("只要设备处于内网或有外壳保护，就无需做针对性安全验证。", False)]
        if (prefix, i) in {("Z", 12), ("Y", 6), ("Y", 37)}:
            choices.append(("安全设计应记录威胁模型、假设和可验证证据，而非依赖口头保证。", True))
        if (prefix, i) == ("Y", 49):
            choices.append(("发生异常时，应优先保持证据、限制影响并按授权流程处置。", True))
            choices.append(("将高权限账号和生产密钥共享给所有维护人员可提高响应效率。", False))
        choices = rotate(choices, i + 1)
        answer = letters_for([j for j, (_, ok) in enumerate(choices) if ok])
        opts = [text for text, _ in choices] + ["" for _ in range(7 - len(choices))]
        rows.append([qid, "多选", domain, tier, f"关于“{topic}”，哪些认识或做法正确？", *opts, answer, f"正确项体现了该主题的安全属性和工程控制：{truth}；并应{action}。其余项要么错误描述能力边界，要么以无关控制替代必要防护。", tag])
    return rows


